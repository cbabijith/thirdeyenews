import { test, expect, type BrowserContext, type APIRequestContext } from '@playwright/test'

const ownerId = '00000000-0000-4000-8000-000000000001'
const adminId = '00000000-0000-4000-8000-000000000002'
const staffId = '00000000-0000-4000-8000-000000000003'
const origin = { Origin: 'http://localhost:3100' }
async function login(context: BrowserContext, request: APIRequestContext, role = 'owner') {
  const session = await (await request.get(`http://127.0.0.1:54329/__test/session?role=${role}`)).json()
  await context.addCookies([{ name: 'sb-127-auth-token', value: `base64-${Buffer.from(JSON.stringify(session)).toString('base64url')}`, domain: 'localhost', path: '/' }])
}

test.beforeEach(async ({ request }) => { await request.post('http://127.0.0.1:54329/__test/reset') })

test('mobile member lifecycle, password visibility, reset and deletion', async ({ page, context, request }) => {
  await login(context, request)
  await page.setViewportSize({ width: 375, height: 812 })
  await page.goto('/team')
  await expect(page.getByRole('heading', { name: 'Team', exact: true })).toBeVisible()
  await expect(page.getByRole('navigation', { name: 'Mobile navigation' }).getByRole('link', { name: 'Team' })).toBeVisible()
  await expect(page.getByText('Staff Member', { exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.getByRole('button', { name: 'Add member', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Full name').fill('New Reporter')
  await dialog.getByLabel('Email address').fill('reporter@example.com')
  await dialog.getByRole('button', { name: 'Generate password' }).click()
  const initialPassword = await dialog.locator('#new-password').inputValue()
  await expect(dialog.locator('#confirm-password')).toHaveValue(initialPassword)
  await dialog.getByRole('button', { name: 'Show password', exact: true }).first().click()
  await expect(dialog.locator('#new-password')).toHaveAttribute('type', 'text')
  await dialog.getByRole('button', { name: 'Hide password' }).click()
  await expect(dialog.locator('#new-password')).toHaveAttribute('type', 'password')
  await dialog.getByRole('button', { name: 'Add member', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.getByText('New Reporter', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Edit New Reporter', exact: true }).click()
  await dialog.getByLabel('Full name').fill('Senior Reporter')
  await dialog.getByRole('button', { name: 'Save changes' }).click()
  await expect(page.getByText('Senior Reporter', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Reset password for Senior Reporter' }).click()
  await dialog.locator('#new-password').fill('ReplacementPassword123!')
  await dialog.locator('#confirm-password').fill('MismatchPassword123!')
  await dialog.getByRole('button', { name: 'Reset password', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('do not match')
  await dialog.locator('#confirm-password').fill('ReplacementPassword123!')
  await dialog.getByRole('button', { name: 'Reset password', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  const signIn = (password: string) => request.post('http://127.0.0.1:54329/auth/v1/token', { data: { email: 'reporter@example.com', password } })
  expect((await signIn(initialPassword)).status()).toBe(400)
  expect((await signIn('ReplacementPassword123!')).status()).toBe(200)
  await page.getByRole('button', { name: 'Delete Senior Reporter', exact: true }).click()
  await expect(dialog.getByRole('button', { name: 'Delete member', exact: true })).toBeDisabled()
  await dialog.getByLabel('Type reporter@example.com to confirm').fill('reporter@example.com')
  await dialog.getByRole('button', { name: 'Delete member', exact: true }).click()
  await expect(page.getByText('Senior Reporter', { exact: true })).not.toBeVisible()
  expect((await signIn('ReplacementPassword123!')).status()).toBe(400)
})

test('server rejects unauthenticated, lower-role, self and protected account mutations', async ({ context, request }) => {
  expect((await context.request.get('/api/team')).status()).toBe(401)
  await login(context, request, 'staff')
  expect((await context.request.get('/api/team')).status()).toBe(403)
  expect((await context.request.patch(`/api/team/${adminId}`, { headers: origin, data: { action: 'password', password: 'NewPassword123!', confirmPassword: 'NewPassword123!' } })).status()).toBe(403)
  await login(context, request, 'admin')
  expect((await context.request.delete(`/api/team/${ownerId}`, { headers: origin, data: { confirmEmail: 'owner@example.com' } })).status()).toBe(403)
  expect((await context.request.delete(`/api/team/${adminId}`, { headers: origin, data: { confirmEmail: 'admin@example.com' } })).status()).toBe(403)
  expect((await context.request.post('/api/team', { headers: origin, data: { full_name: 'Escalation', email: 'escalation@example.com', role: 'superadmin', password: 'NewPassword123!', confirmPassword: 'NewPassword123!' } })).status()).toBe(403)
  expect((await context.request.patch(`/api/team/${staffId}`, { headers: { Origin: 'https://evil.example' }, data: { action: 'password' } })).status()).toBe(403)
  expect((await context.request.delete(`/api/team/${staffId}`, { headers: origin, data: { confirmEmail: 'wrong' } })).status()).toBe(400)
})

