test('own password requires current password and returns to sign in', async ({ page, context, request }) => {
  await login(context, request)
  await page.goto('/team')
  await page.getByRole('button', { name: 'Change my password' }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Current password', { exact: true }).fill('wrong-password')
  await dialog.getByLabel('New password', { exact: true }).fill('ChangedOwnerPassword123!')
  await dialog.getByLabel('Confirm password', { exact: true }).fill('ChangedOwnerPassword123!')
  await dialog.getByRole('button', { name: 'Save changes' }).click()
  await expect(dialog.getByRole('alert')).toContainText('current password is incorrect')
  await dialog.getByLabel('Current password', { exact: true }).fill('OriginalPassword123!')
  await dialog.getByRole('button', { name: 'Save changes' }).click()
  await expect(page).toHaveURL(/\/login\?password=changed/)
})

test('responsive layouts, keyboard dismissal and pagination', async ({ page, context, request }, testInfo) => {
  await login(context, request)
  for (let index = 0; index < 12; index++) {
    const response = await context.request.post('/api/team', { headers: origin, data: { full_name: `Reporter ${index}`, email: `reporter-${index}@example.com`, role: 'staff', password: 'StrongPassword123!', confirmPassword: 'StrongPassword123!' } })
    expect(response.ok()).toBeTruthy()
  }
  await page.goto('/team')
  await expect(page.getByText('Page 1 of 2')).toBeVisible()
  await page.getByRole('button', { name: 'Next page' }).click()
  await expect(page.getByText('Page 2 of 2')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Next page' })).toBeDisabled()
  await page.getByRole('button', { name: 'Previous page' }).click()
  await expect(page.getByText('Page 1 of 2')).toBeVisible()
  for (const width of [320, 768, 1440]) {
    await page.setViewportSize({ width, height: 900 })
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
    const add = page.getByRole('button', { name: 'Add member', exact: true })
    await expect(add).toHaveCSS('background-color', 'rgb(17, 24, 39)')
    await page.screenshot({ path: testInfo.outputPath(`team-${width}.png`), fullPage: true, animations: 'disabled' })
    if (width >= 768) expect((await page.getByRole('main').boundingBox())!.x).toBeGreaterThanOrEqual(256)
    await add.click()
    const dialog = page.getByRole('dialog')
    const bounds = await dialog.boundingBox()
    expect(bounds!.x).toBeGreaterThanOrEqual(0)
    expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(width)
    expect(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth)).toBeTruthy()
    await page.screenshot({ path: testInfo.outputPath(`team-form-${width}.png`), animations: 'disabled' })
    await page.keyboard.press('Escape')
    await expect(dialog).not.toBeVisible()
    await expect(add).toBeFocused()
  }
})
